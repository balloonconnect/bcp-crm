import type { FastifyInstance } from "fastify";
import { z } from "zod";
import { createAlertRuleSchema, updateAlertRuleSchema, createIncidentSchema, postIncidentUpdateSchema } from "@bcp/observability";
import { requirePlatformPermission } from "../plugins/auth-guard";
import { runAllHealthChecks } from "../services/health-checks.service";
import { aggregateOverallHealth, computeUptimePercent } from "@bcp/observability";
import { prisma } from "@bcp/database";
import * as alerts from "../services/alerts.service";
import * as incidents from "../services/incidents.service";

const idParamsSchema = z.object({ id: z.string().uuid() });

export async function monitoringRoutes(app: FastifyInstance) {
  const view = [app.authenticate, requirePlatformPermission("health:view")];
  const manage = [app.authenticate, requirePlatformPermission("system_config:manage")];

  // ── Platform health dashboard ────────────────────────────────────
  app.get("/platform/monitoring/health", { preHandler: view }, async () => {
    const results = await runAllHealthChecks();
    const overall = aggregateOverallHealth(results.map((r) => ({ service: r.service, status: r.status })));
    return { ok: true, data: { status: overall, services: results } };
  });

  app.get("/platform/monitoring/uptime", { preHandler: view }, async (request) => {
    const { days } = z.object({ days: z.coerce.number().int().positive().max(90).default(30) }).parse(request.query);
    const since = new Date(Date.now() - days * 24 * 60 * 60 * 1000);
    const checks = await prisma.serviceHealthCheck.findMany({ where: { checkedAt: { gte: since } }, select: { service: true, status: true } });

    const byService = new Map<string, { status: string }[]>();
    for (const check of checks) {
      const list = byService.get(check.service) ?? [];
      list.push({ status: check.status });
      byService.set(check.service, list);
    }

    const uptime = [...byService.entries()].map(([service, serviceChecks]) => ({ service, uptimePercent: computeUptimePercent(serviceChecks as never) }));
    return { ok: true, data: uptime };
  });

  // ── Alert rules ───────────────────────────────────────────────────
  app.get("/platform/monitoring/alert-rules", { preHandler: view }, async () => ({ ok: true, data: await alerts.listAlertRules() }));

  app.post("/platform/monitoring/alert-rules", { preHandler: manage }, async (request) => {
    const body = createAlertRuleSchema.parse(request.body);
    return { ok: true, data: await alerts.createAlertRule(body, request.auth!.actorId) };
  });

  app.patch("/platform/monitoring/alert-rules/:id", { preHandler: manage }, async (request) => {
    const { id } = idParamsSchema.parse(request.params);
    const body = updateAlertRuleSchema.parse(request.body);
    return { ok: true, data: await alerts.updateAlertRule(id, body, request.auth!.actorId) };
  });

  app.delete("/platform/monitoring/alert-rules/:id", { preHandler: manage }, async (request) => {
    const { id } = idParamsSchema.parse(request.params);
    await alerts.deleteAlertRule(id, request.auth!.actorId);
    return { ok: true, data: null };
  });

  app.get("/platform/monitoring/triggered-alerts", { preHandler: view }, async (request) => {
    const { activeOnly } = z.object({ activeOnly: z.coerce.boolean().default(false) }).parse(request.query);
    return { ok: true, data: await alerts.listTriggeredAlerts(activeOnly) };
  });

  // ── Incidents (platform admin) ────────────────────────────────────
  app.get("/platform/monitoring/incidents", { preHandler: view }, async () => ({ ok: true, data: await incidents.listIncidents() }));

  app.post("/platform/monitoring/incidents", { preHandler: manage }, async (request) => {
    const body = createIncidentSchema.parse(request.body);
    return { ok: true, data: await incidents.createIncident(body, request.auth!.actorId) };
  });

  app.post("/platform/monitoring/incidents/:id/updates", { preHandler: manage }, async (request) => {
    const { id } = idParamsSchema.parse(request.params);
    const body = postIncidentUpdateSchema.parse(request.body);
    return { ok: true, data: await incidents.postIncidentUpdate(id, body, request.auth!.actorId) };
  });

  // ── Public status page — no auth, deliberately: a status page is only useful if anyone can see it ──
  app.get("/status/public", async () => {
    // Reads the most recent *persisted* check per service rather than running live checks on every
    // anonymous page view — health checks are generated by the platform-admin dashboard view and,
    // in a real deployment, a periodic scheduled job (see docs/monitoring-and-observability.md),
    // never driven by public traffic.
    const allServices = ["api", "database", "redis", "storage", "ai_provider", "whatsapp", "payment_provider", "queue"];
    const latestPerService = await Promise.all(
      allServices.map((service) => prisma.serviceHealthCheck.findFirst({ where: { service: service as never }, orderBy: { checkedAt: "desc" } })),
    );
    const currentChecks = latestPerService.filter((c: { service: string; status: string } | null): c is { service: string; status: string } => c !== null);
    const overall = currentChecks.length > 0 ? aggregateOverallHealth(currentChecks.map((c: { service: string; status: string }) => ({ service: c.service, status: c.status as never }))) : "healthy";

    const recentIncidents = await incidents.listPublicIncidents(20);

    const since = new Date(Date.now() - 90 * 24 * 60 * 60 * 1000);
    const checks = await prisma.serviceHealthCheck.findMany({ where: { checkedAt: { gte: since } }, select: { service: true, status: true } });
    const byService = new Map<string, { status: string }[]>();
    for (const check of checks) {
      const list = byService.get(check.service) ?? [];
      list.push({ status: check.status });
      byService.set(check.service, list);
    }
    const uptime90d = [...byService.entries()].map(([service, serviceChecks]) => ({ service, uptimePercent: computeUptimePercent(serviceChecks as never) }));

    return { ok: true, data: { status: overall, services: currentChecks.map((c: { service: string; status: string }) => ({ service: c.service, status: c.status })), uptime90d, incidents: recentIncidents } };
  });
}
